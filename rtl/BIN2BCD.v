`timescale 1ns/1ps
// =============================================================================
// BIN2BCD.v : преобразователь двоичного числа в упакованный BCD (алгоритм
//             double dabble). Комбинационная схема.
//             Аппаратная часть кастомной инструкции BIN2BCD (задача №21).
//
//   bin[15:0]  -> bcd[19:0] = 5 десятичных цифр (по 4 бита на цифру)
//   bcd[3:0]   единицы, bcd[7:4] десятки, bcd[11:8] сотни,
//   bcd[15:12] тысячи,  bcd[19:16] десятки тысяч.
//   В ALU используются младшие 4 цифры bcd[15:0]; признак переполнения
//   (число >= 10000) = bcd[19:16] != 0.
// =============================================================================
module BIN2BCD (
    input  wire [15:0] bin,
    output wire [19:0] bcd
);
    reg [35:0] sh;     // [35:16] - BCD-цифры, [15:0] - сдвигаемое двоичное число
    integer    i;

    always @* begin
        sh = {20'd0, bin};
        for (i = 0; i < 16; i = i + 1) begin
            // Перед каждым сдвигом: если цифра >= 5, прибавить 3
            if (sh[35:32] >= 4'd5) sh[35:32] = sh[35:32] + 4'd3;
            if (sh[31:28] >= 4'd5) sh[31:28] = sh[31:28] + 4'd3;
            if (sh[27:24] >= 4'd5) sh[27:24] = sh[27:24] + 4'd3;
            if (sh[23:20] >= 4'd5) sh[23:20] = sh[23:20] + 4'd3;
            if (sh[19:16] >= 4'd5) sh[19:16] = sh[19:16] + 4'd3;
            sh = sh << 1;
        end
    end

    assign bcd = sh[35:16];
endmodule
