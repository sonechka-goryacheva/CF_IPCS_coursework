; =============================================================================
; sort.asm : пузырьковая сортировка 10 слов по возрастанию (беззнаково)
;            Та же программа, что в sw/sort_rom.mem (написана вручную в этапе 2),
;            но на ассемблере. Результат ассемблера сравнивается с ручным кодом.
;
; Регистры: R1 = i (верхняя граница внутреннего цикла)
;           R2 = j (адрес элемента)   R3 = a[j]   R4 = a[j+1]
; =============================================================================

        .equ N, 10                  ; количество элементов

        .data                       ; --- исходные данные: загружаются в RAM ---
array:  .word 42, 7, 1000, 7, 0, 65535, 300, 15, 99, 3

        .text                       ; --- программа: загружается в ROM ---
start:  LDI   R1, array+N-1         ; i = адрес последнего элемента (9)
outer:  LDI   R2, array             ; j = адрес первого элемента (0)
inner:  CMP   R2, R1                ; j - i
        BHS   inner_done            ; j >= i: проход закончен
        LOAD  R3, [R2+0]            ; R3 = a[j]
        LOAD  R4, [R2+1]            ; R4 = a[j+1]
        CMP   R4, R3                ; a[j+1] - a[j]
        BHS   no_swap               ; a[j+1] >= a[j]: обмен не нужен
        STORE R4, [R2+0]            ; a[j]   = старое a[j+1]
        STORE R3, [R2+1]            ; a[j+1] = старое a[j]
no_swap: ADDI R2, R2, 1             ; j++
        JUMP  inner
inner_done:
        ADDI  R1, R1, -1            ; i--
        BNE   outer                 ; i != 0: следующий проход
        HLT
