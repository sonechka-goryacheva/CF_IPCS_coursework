; =============================================================================
; vending.asm : автомат с едой (задача №4). Один товар, цена PRICE.
;
; Ввод:   клавиши 1, 2, 5 - монеты 1, 2, 5 руб.; 15 - отмена (возврат денег).
;         Остальные клавиши в режиме приёма монет игнорируются.
; Вывод:  индикаторы (SEG) показывают баланс, после покупки/отмены - сдачу.
;         LED0 (бит 0) - товар выдан;  LED1 (бит 1) - сдача/возврат.
;         Светодиоды и есть признак режима: оба погашены - показан баланс,
;         горит LED1 - показана сдача (возврат).
; Состояния: R5 = 0 - приём монет; R5 = 1 - операция завершена (покупка или
;         возврат): любое следующее нажатие только сбрасывает автомат
;         (баланс 0, светодиоды погашены) и больше ничего не делает.
; Отмена при нулевом балансе ничего не делает.
;
; Регистры: R1 = баланс, R2 = код клавиши / временный, R3, R4 = временные,
;           R5 = состояние, R6 = база MMIO (0xFF00), R7 = регистр связи (CALL/RET)
; =============================================================================

        .equ MMIO,        0xFF00    ; база MMIO-регистров
        .equ KEY_STATUS,  0         ; смещения регистров от базы
        .equ KEY_DATA,    1
        .equ LED,         2
        .equ SEG,         3
        .equ PRICE,       7         ; цена товара, руб. (до 255)
        .equ K_CANCEL,    15        ; код клавиши отмены
        .equ LED_ITEM,    1         ; LED0: товар выдан
        .equ LED_CHANGE,  2         ; LED1: сдача / возврат

        .text
start:  LI    R6, MMIO              ; R6 = 0xFF00

reset:  LDI   R1, 0                 ; баланс = 0
        LDI   R5, 0                 ; состояние: приём монет
        LDI   R3, 0
        STORE R3, [R6+LED]          ; светодиоды погашены
        CALL  show                  ; индикаторы: 0 (R3 = 0)

wait:   LOAD  R2, [R6+KEY_STATUS]   ; ждём нажатия клавиши
        SHR   R2, R2                ; C = бит VALID
        BLO   wait                  ; C = 0: клавиши нет
        LOAD  R2, [R6+KEY_DATA]     ; R2 = код клавиши (VALID сбрасывается)

        ADDI  R0, R5, -1            ; состояние == 1 (завершено)?
        BEQ   reset                 ; да: нажатие только сбрасывает автомат

        ADDI  R0, R2, -1            ; клавиша 1?
        BEQ   coin1
        ADDI  R0, R2, -2            ; клавиша 2?
        BEQ   coin2
        ADDI  R0, R2, -5            ; клавиша 5?
        BEQ   coin5
        ADDI  R0, R2, -K_CANCEL     ; клавиша отмены?
        BEQ   cancel
        JUMP  wait                  ; прочие клавиши игнорируются

coin1:  ADDI  R1, R1, 1
        JUMP  got_coin
coin2:  ADDI  R1, R1, 2
        JUMP  got_coin
coin5:  ADDI  R1, R1, 5

got_coin:
        MOV   R3, R1
        CALL  show                  ; показать баланс
        LDI   R4, PRICE
        CMP   R1, R4                ; баланс - цена
        BLO   wait                  ; баланс < цены: ждём ещё монет

        ; --- покупка: баланс >= цены ---
        SUB   R3, R1, R4            ; R3 = сдача = баланс - цена
        LDI   R2, LED_ITEM          ; LED0: товар выдан
        ADDI  R0, R3, 0             ; сдача == 0 ?
        BEQ   buy_led
        LDI   R4, LED_CHANGE
        OR    R2, R2, R4            ; + LED1: есть сдача
buy_led:
        STORE R2, [R6+LED]
        CALL  show                  ; показать сдачу (R3)
        LDI   R5, 1                 ; состояние: завершено
        JUMP  wait

        ; --- отмена: вернуть внесённую сумму ---
cancel: ADDI  R0, R1, 0             ; баланс == 0 ?
        BEQ   wait                  ; возвращать нечего: ничего не делаем
        LDI   R2, LED_CHANGE
        STORE R2, [R6+LED]          ; LED1: возврат
        MOV   R3, R1
        CALL  show                  ; показать возвращаемую сумму
        LDI   R5, 1                 ; состояние: завершено
        JUMP  wait

; -----------------------------------------------------------------------------
; show: вывести число R3 (0..9999) на индикаторы, гася ведущие нули.
;       Портит R2, R3, R4. Единицы показываются всегда ("0", а не пусто).
; -----------------------------------------------------------------------------
show:   BIN2BCD R2, R3              ; R2 = упакованный BCD (копия для сравнений)
        MOV   R3, R2                ; R3 = выводимое значение
        LI    R4, 0x1000
        CMP   R2, R4                ; BCD >= 0x1000: тысячи значащие
        BHS   show_out
        LI    R4, 0xF000
        OR    R3, R3, R4            ; погасить разряд тысяч
        LI    R4, 0x0100
        CMP   R2, R4                ; BCD >= 0x0100: сотни значащие
        BHS   show_out
        LI    R4, 0x0F00
        OR    R3, R3, R4            ; погасить разряд сотен
        LI    R4, 0x0010
        CMP   R2, R4                ; BCD >= 0x0010: десятки значащие
        BHS   show_out
        LI    R4, 0x00F0
        OR    R3, R3, R4            ; погасить разряд десятков
show_out:
        STORE R3, [R6+SEG]
        RET
